/**
 * Rebuild content/tools/index.ts from the JSON files and validate them with Zod.
 * Run this after adding or editing a fiche: node scripts/catalog-index.mjs
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"
import { createRequire } from "module"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const dir = path.join(root, "content", "tools")
const files = fs.readdirSync(dir).filter((name) => name.endsWith(".json")).sort()

if (!files.length) {
  console.error("No JSON files in content/tools")
  process.exit(1)
}

const require = createRequire(import.meta.url)
const { z } = require("zod")

const CATEGORY_IDS = [
  "text",
  "image",
  "audio",
  "video",
  "coding",
  "marketing",
  "productivity",
  "data-processing",
  "design",
]
const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/)
const toolSchema = z.object({
  id: z.string().regex(/^[a-z0-9]+(?:[-_][a-z0-9]+)*$/),
  name: z.string().min(1),
  url: z.string().url(),
  affiliateUrl: z.union([z.literal(""), z.string().url()]).optional(),
  status: z.enum(["active", "renamed", "sunset", "duplicate-of"]),
  successorId: z.string().optional(),
  statusNote: z.string().optional(),
  summary: z.string().min(1),
  description: z.string().min(1),
  categories: z.array(z.enum(CATEGORY_IDS)).min(1),
  tags: z.array(z.string().min(1)).min(1),
  pricing: z.object({
    model: z.enum(["free", "freemium", "paid", "open-source"]),
    label: z.enum(["Free", "Freemium", "Premium", "Open source"]),
    note: z.string().optional(),
    verified: z.boolean(),
    sourceUrl: z.string().url().optional(),
  }),
  logo: z.string(),
  image: z.string(),
  dateAdded: isoDate.nullable(),
  dateAddedNote: z.string().optional(),
  lastVerified: isoDate.nullable(),
  sources: z.array(z.string().url()).optional(),
  features: z.array(z.string().min(1)).optional(),
  howToUse: z.array(z.object({
    title: z.string().min(1),
    description: z.string().min(1),
    links: z.array(z.object({ label: z.string().min(1), url: z.string().url() })).optional(),
  })).optional(),
})

const ids = new Set()
const errors = []
for (const file of files) {
  const json = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"))
  const parsed = toolSchema.safeParse(json)
  if (!parsed.success) {
    errors.push(`${file}: ${parsed.error.issues.map((i) => `${i.path.join(".")} ${i.message}`).join("; ")}`)
    continue
  }
  if (parsed.data.id !== file.replace(/\.json$/, "")) {
    errors.push(`${file}: id is ${parsed.data.id}`)
  }
  if (ids.has(parsed.data.id)) errors.push(`${file}: duplicate id`)
  ids.add(parsed.data.id)
  if (parsed.data.successorId && !files.includes(`${parsed.data.successorId}.json`) && parsed.data.successorId !== parsed.data.id) {
    // successor may be added in the same folder; checked after the loop
  }
}

for (const file of files) {
  const json = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"))
  if (json.successorId && !ids.has(json.successorId)) {
    errors.push(`${file}: successorId ${json.successorId} does not exist`)
  }
}

if (errors.length) {
  console.error(errors.join("\n"))
  process.exit(1)
}

const imports = files
  .map((file) => {
    const id = file.replace(/\.json$/, "")
    const ident = id.replace(/-/g, "_")
    return `import ${ident} from "./${id}.json"`
  })
  .join("\n")
const names = files.map((file) => file.replace(/\.json$/, "").replace(/-/g, "_")).join(", ")
const index = `// Generated by scripts/catalog-index.mjs. Do not edit by hand.\nimport { toolSchema } from "@/lib/tool-schema"\n${imports}\n\nconst rawTools = [${names}]\n\nexport const catalogTools = rawTools.map((tool) => toolSchema.parse(tool))\n`
fs.writeFileSync(path.join(dir, "index.ts"), index)
console.log(`Validated ${files.length} tools and wrote content/tools/index.ts`)
