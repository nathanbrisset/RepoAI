/**
 * Rebuild content/tools/index.ts from the JSON files and validate them with Zod.
 * Run this after adding or editing a fiche: node scripts/catalog-index.mjs
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"
import { createRequire } from "module"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const dir = path.join(root, "content", "tools")
const logoDir = path.join(root, "public", "logos")
const generatedDir = path.join(root, "lib", "generated")
const files = fs.readdirSync(dir).filter((name) => name.endsWith(".json")).sort()

if (!files.length) {
  console.error("No JSON files in content/tools")
  process.exit(1)
}

const require = createRequire(import.meta.url)
const { z } = require("zod")

const taxonomy = JSON.parse(fs.readFileSync(path.join(root, "content/taxonomy.json"), "utf8"))
const CATEGORY_IDS = [...taxonomy.categories.map((category) => category.id), ...taxonomy.legacyIds]
const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/)
const toolSchema = z.object({
  id: z.string().regex(/^[a-z0-9]+(?:[-_][a-z0-9]+)*$/),
  name: z.string().min(1),
  url: z.union([z.literal(""), z.string().url()]),
  affiliateUrl: z.union([z.literal(""), z.string().url()]).optional(),
  status: z.enum(["active", "inactive", "renamed", "sunset", "duplicate-of"]),
  successorId: z.string().optional(),
  statusNote: z.string().optional(),
  summary: z.string().min(1),
  description: z.string().min(1),
  categories: z.array(z.enum(CATEGORY_IDS)).min(1),
  tags: z.array(z.string().min(1)).min(1),
  pricing: z.object({
    model: z.enum(["free", "freemium", "paid", "open-source", "enterprise", "usage-based", "one-time"]).optional(),
    label: z.enum(["Free", "Freemium", "Premium", "Open source", "Enterprise", "Usage-based", "One-time"]).optional(),
    note: z.string().optional(),
    verified: z.boolean(),
    sourceUrl: z.string().url().optional(),
    uncertain: z.boolean().optional(),
  }).superRefine((value, ctx) => {
    if (value.uncertain) return
    if (!value.model) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["model"], message: "required unless the price is uncertain" })
    if (!value.label) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["label"], message: "required unless the price is uncertain" })
  }),
  logo: z.string(),
  image: z.string(),
  dateAdded: isoDate.nullable(),
  dateAddedNote: z.string().optional(),
  lastVerified: isoDate.nullable(),
  sources: z.array(z.string().url()).optional(),
  features: z.array(z.string().min(1)).optional(),
  howToUse: z.array(z.object({
    title: z.string().min(1),
    description: z.string().min(1),
    links: z.array(z.object({ label: z.string().min(1), url: z.string().url() })).optional(),
  })).optional(),
  hqCountry: z.string().regex(/^[A-Z]{2}$/).optional(),
  hqCountrySource: z.enum(["verified", "import", "inferred"]).optional(),
})

const ids = new Set()
const errors = []
for (const file of files) {
  const json = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"))
  const parsed = toolSchema.safeParse(json)
  if (!parsed.success) {
    errors.push(`${file}: ${parsed.error.issues.map((i) => `${i.path.join(".")} ${i.message}`).join("; ")}`)
    continue
  }
  if (parsed.data.id !== file.replace(/\.json$/, "")) {
    errors.push(`${file}: id is ${parsed.data.id}`)
  }
  if (ids.has(parsed.data.id)) errors.push(`${file}: duplicate id`)
  ids.add(parsed.data.id)
  if (parsed.data.successorId && !files.includes(`${parsed.data.successorId}.json`) && parsed.data.successorId !== parsed.data.id) {
    // successor may be added in the same folder; checked after the loop
  }
}

for (const file of files) {
  const json = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"))
  if (json.successorId && !ids.has(json.successorId)) {
    errors.push(`${file}: successorId ${json.successorId} does not exist`)
  }
}

if (errors.length) {
  console.error(errors.join("\n"))
  process.exit(1)
}

function importIdent(id) {
  const base = id.replace(/-/g, "_")
  return /^\d/.test(base) ? `tool_${base}` : base
}

const imports = files
  .map((file) => {
    const id = file.replace(/\.json$/, "")
    return `import ${importIdent(id)} from "./${id}.json"`
  })
  .join("\n")
const names = files.map((file) => importIdent(file.replace(/\.json$/, ""))).join(", ")
const index = `// Generated by scripts/catalog-index.mjs. Do not edit by hand.\nimport { toolSchema } from "@/lib/tool-schema"\n${imports}\n\nconst rawTools = [${names}]\n\nexport const catalogTools = rawTools.map((tool) => toolSchema.parse(tool))\n`
fs.writeFileSync(path.join(dir, "index.ts"), index)

fs.mkdirSync(generatedDir, { recursive: true })
const logoIds = fs.existsSync(logoDir)
  ? fs
      .readdirSync(logoDir)
      .filter((name) => /\.(png|webp|jpg|svg)$/i.test(name))
      .map((name) => name.replace(/\.(png|webp|jpg|svg)$/i, ""))
      .sort()
  : []
const logoModule = `// Generated by scripts/catalog-index.mjs. Do not edit by hand.\nexport const localLogoIds = ${JSON.stringify(logoIds)} as const\n`
fs.writeFileSync(path.join(generatedDir, "local-logos.ts"), logoModule)

console.log(`Validated ${files.length} tools and wrote content/tools/index.ts (${logoIds.length} local logos)`)
