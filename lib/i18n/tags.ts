export function translateTags(tags?: string[], tagsFr?: string[]) {
  if (!tags) return tags
  return tags.map((tag, index) => {
    const explicit = tagsFr?.[index]
    if (explicit && tagsFr && tagsFr.length === tags.length) return explicit
    return translateTag(tag)
  })
}
