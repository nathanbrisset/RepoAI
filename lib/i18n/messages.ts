const dictionaries = { en, fr }

export function translate(locale: Locale, key: string, vars?: MessageVars): string {
  const parts = key.split(".")
  let value: unknown = dictionaries[locale]
  for (const part of parts) {
    if (value && typeof value === "object" && part in (value as Record<string, unknown>)) {
      value = (value as Record<string, unknown>)[part]
    } else {
      value = undefined
      break
    }
  }
  if (typeof value !== "string") {
    if (locale !== "en") return translate("en", key, vars)
    return key
  }
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""))
}

export function categoryCopy(locale: Locale, id: string) {
  const table = dictionaries[locale].category as Record<string, { name: string; description: string; about: string }>
  return table[id] || dictionaries.en.category[id as keyof typeof en.category]
}

export function pricingLabel(locale: Locale, label?: string | null) {
  if (!label) return ""
  if (locale !== "fr") return label
  const table = fr.pricing as Record<string, string>
  return table[label] || label
}

export function statusLabel(locale: Locale, status?: string | null) {
  if (!status) return ""
  const table = dictionaries[locale].status as Record<string, string>
  return table[status] || status
}
